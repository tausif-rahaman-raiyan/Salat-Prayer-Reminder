/**
 * Returns a stable daily quote based on Bangladesh local date YYYY-MM-DD
 * Supports 'en' or 'bn' language
 */
export function getDailyQuote(dateStr, lang = 'en') {
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash * 31 + dateStr.charCodeAt(i)) >>> 0;
  }
  const item = ISLAMIC_QUOTES[hash % ISLAMIC_QUOTES.length];
  
  if (lang === 'bn') {
    return {
      id: item.id,
      text: item.textBn,
      reference: item.refBn,
      type: item.type
    };
  }

  return {
    id: item.id,
    text: item.textEn,
    reference: item.refEn,
    type: item.type
  };
}
